/**
 * Writes src/theme.css: the colour palettes the app uses, as CSS variables
 * (task 37.3, Requirement 14.2).
 *
 * Light: Tailwind's palettes as they are. Dark (`html.dark`): every palette
 * reversed (50 ↔ 950, 100 ↔ 900 …) and `white` becomes a dark surface, so
 * the same classes (bg-white, text-gray-900, bg-indigo-600) read well in both
 * themes without dark: variants on every element. `indigo` is the accent:
 * `html[data-accent=…]` swaps in another palette.
 *
 * Run after changing palettes:  node scripts/generate-theme.mjs
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import colors from "tailwindcss/colors.js";

const SHADES = ["50", "100", "200", "300", "400", "500", "600", "700", "800", "900", "950"];
const BASE = { gray: colors.gray, red: colors.red, green: colors.green, amber: colors.amber, yellow: colors.yellow };
const ACCENTS = {
  indigo: colors.indigo,
  blue: colors.blue,
  emerald: colors.emerald,
  violet: colors.violet,
  rose: colors.rose,
  amber: colors.amber,
};

const rgb = (hex) => {
  const n = parseInt(hex.slice(1), 16);
  return `${(n >> 16) & 255} ${(n >> 8) & 255} ${n & 255}`;
};

function vars(name, palette, reversed) {
  return SHADES.map((shade, i) => {
    const source = reversed ? SHADES[SHADES.length - 1 - i] : shade;
    return `  --c-${name}-${shade}: ${rgb(palette[source])};`;
  }).join("\n");
}

const out = ["/* Generated by scripts/generate-theme.mjs — do not edit by hand. */", ""];

out.push(":root {", "  color-scheme: light;", `  --c-white: ${rgb("#ffffff")};`);
for (const [name, palette] of Object.entries(BASE)) out.push(vars(name, palette, false));
out.push(vars("accent", ACCENTS.indigo, false), "}", "");

out.push("html.dark {", "  color-scheme: dark;", `  --c-white: ${rgb(colors.gray[900])};`);
for (const [name, palette] of Object.entries(BASE)) out.push(vars(name, palette, true));
out.push(vars("accent", ACCENTS.indigo, true), "}", "");

for (const [name, palette] of Object.entries(ACCENTS)) {
  out.push(`html[data-accent="${name}"] {`, vars("accent", palette, false), "}");
  out.push(`html.dark[data-accent="${name}"] {`, vars("accent", palette, true), "}", "");
}

const target = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "src", "theme.css");
writeFileSync(target, out.join("\n"));
console.log(`Wrote ${target}`);
